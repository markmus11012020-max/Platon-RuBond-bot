ALIASES = {
    "iis": "iis3",
    "иис": "iis3",
    "iis3": "iis3",
    "iis-3": "iis3",
    "ндфл": "ndfl",
    "tax": "ndfl",
    "налог": "ndfl",
    "купон": "coupons",
    "coupons": "coupons",
}


def get_topic(topic: str | None) -> Topic:
    key = (topic or "").strip().lower()
    key = ALIASES.get(key, key)
    return TOPICS.get(key, TOPICS["ndfl"])


def format_topic(topic: str | None) -> str:
    item = get_topic(topic)
    lines = [
        f"📚 {item.title}",
        f"Актуальность: {EFFECTIVE}",
        "",
        item.text,
        "",
        "Источники:",
    ]
    lines.extend(f"• {source}" for source in item.sources)
    lines.append("")
    lines.append(DISCLAIMER)
    return "\n".join(lines)


